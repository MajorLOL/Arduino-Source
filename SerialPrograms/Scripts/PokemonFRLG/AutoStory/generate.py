#!/usr/bin/env python3
"""
FRLG Autostory generator.

Builds the whole story (story_spec.py) for each starter and writes:
  PokemonFRLG_AutoStoryData.h   C++ data for Pokemon Automation
  story.json                    everything, for inspection
  STORY.md                      overview per segment
  images/                       every leg drawn on its maps (Bulbasaur variant,
                                plus legs that differ for the other starters)

Usage:
  python3 generate.py --decomp /path/to/pokefirered --out ./out [--no-images]
"""

import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from frlg_data import Decomp                      # noqa: E402
from engine import GameData                       # noqa: E402
from story import Builder, StoryError             # noqa: E402
import story_spec                                 # noqa: E402

DPAD = {"up": "DPAD_UP", "down": "DPAD_DOWN", "left": "DPAD_LEFT", "right": "DPAD_RIGHT", None: "DPAD_NONE"}


def cstr(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


DIR_STEPS = ("GRIND", "OSCILLATE", "PUSH")


def readable_map_name(name):
    """VermilionCity_PokemonCenter_1F -> Vermilion City Pokemon Center 1F."""
    words = []
    for part in name.split("_"):
        part = re.sub(r"(?<=[a-z])(?=[A-Z0-9])|(?<=[A-Z])(?=[A-Z][a-z])", " ", part)
        words.append(part)
    return " ".join(words)


def write_cpp(results, path, decomp):
    """Flat constexpr arrays (fast to compile, no dynamic initialization).
    Leg lists (legs_a/b/c of a step) are offsets into LEG_LISTS, where the
    entry at the offset is the count, followed by the leg indexes."""
    L = []
    L.append("/*  Pokemon FRLG Autostory Data")
    L.append(" *")
    L.append(" *  From: https://github.com/PokemonAutomation/")
    L.append(" *")
    L.append(" *  GENERATED by SerialPrograms/Scripts/PokemonFRLG/AutoStory/generate.py")
    L.append(" *  from the pret/pokefirered map data and story_spec.py. Do not edit by hand.")
    L.append(" *")
    L.append(" */")
    L.append("")
    L.append("#ifndef PokemonAutomation_PokemonFRLG_AutoStoryData_H")
    L.append("#define PokemonAutomation_PokemonFRLG_AutoStoryData_H")
    L.append("")
    L.append('#include "VideoGames/PokemonFRLG/Programs/AutoStory/PokemonFRLG_AutoStoryScript.h"')
    L.append("")
    L.append("namespace PokemonAutomation{")
    L.append("namespace NintendoSwitch{")
    L.append("namespace PokemonFRLG{")
    L.append("namespace AutoStoryData{")
    L.append("")
    for variant, (legs, segments) in results.items():
        ns = "Data_" + variant
        L.append("namespace %s{" % ns)
        L.append("")
        #  Runs
        L.append("inline constexpr StoryRun RUNS[] = {")
        run_index = []
        n = 0
        for leg in legs:
            run_index.append(n)
            for d, c, k in leg["runs"]:
                L.append("    {%s, %d, RunKind::%s}," % (DPAD[d], c, k))
                n += 1
        if n == 0:
            L.append("    {DPAD_NONE, 0, RunKind::WALK},")
        L.append("};")
        L.append("")
        #  The maps the legs start on (for the messages: where a step
        #  expects the player).
        map_ids = sorted({leg["start"][0] for leg in legs})
        map_index = {mid: i for i, mid in enumerate(map_ids)}
        L.append("inline constexpr const char* MAP_NAMES[] = {")
        for mid in map_ids:
            L.append("    %s," % cstr(readable_map_name(decomp.maps[mid].name)))
        L.append("};")
        L.append("")
        #  Legs
        L.append("inline constexpr StoryLeg LEGS[] = {")
        for i, leg in enumerate(legs):
            L.append("    {%s, %d, %d, %s, %s, %s, LegEnd::%s, %s, %s, MapPreview::%s, %s, %d, %d, %d},  //  %d" % (
                cstr(leg["name"]), run_index[i], len(leg["runs"]),
                DPAD[leg["start_facing"]], DPAD[leg["push"]], DPAD[leg["face"]],
                leg["end"], "true" if leg["dark"] else "false", "true" if leg["dest_dark"] else "false",
                leg.get("preview") or "NONE", "true" if leg.get("run") else "false",
                map_index[leg["start"][0]], leg["start"][1], leg["start"][2], i))
        L.append("};")
        L.append("")
        #  Leg lists and steps
        lists = [0]     # offset 0 = the empty list
        steps_out = []
        seg_out = []
        for seg in segments:
            first = len(steps_out)
            for st in seg["steps"]:
                offs = []
                for key in ("legs_to_grass", "legs_to_nurse", "legs_back"):
                    lst = st.get(key, [])
                    if not lst:
                        offs.append(0)
                        continue
                    offs.append(len(lists))
                    lists.append(len(lst))
                    lists.extend(lst)
                d = st.get("dir")
                if d is None and st["type"] in DIR_STEPS:
                    d = st.get("text") or None
                steps_out.append("    {StepType::%s, %s, %d, %d, %d, %d, %d, %d, %s, %s, %d, %d, %d}," % (
                    st["type"], cstr(st.get("label", "")), st.get("leg", -1),
                    int(st.get("p0", 0)), int(st.get("p1", 0)), int(st.get("p2", -1)), int(st.get("p3", 0)),
                    int(st.get("p4", 0)),
                    DPAD[d], cstr(st.get("text", "")), offs[0], offs[1], offs[2]))
            seg_out.append("    {%s, %s, %d, %s, %d, %d}," % (
                cstr(seg["id"]), cstr(seg["title"]), seg["chapter"],
                "true" if seg["has_dex"] else "false", first, len(steps_out) - first))
        L.append("inline constexpr int32_t LEG_LISTS[] = {")
        for i in range(0, len(lists), 20):
            L.append("    " + ", ".join(str(x) for x in lists[i:i + 20]) + ",")
        L.append("};")
        L.append("")
        L.append("inline constexpr StoryStep STEPS[] = {")
        L.extend(steps_out)
        L.append("};")
        L.append("")
        L.append("inline constexpr StorySegment SEGMENTS[] = {")
        L.extend(seg_out)
        L.append("};")
        L.append("")
        L.append("}")
        L.append("")
        L.append("inline const StoryScript& story_%s(){" % variant)
        L.append("    static const StoryScript script{")
        L.append("        %s::RUNS, std::size(%s::RUNS)," % (ns, ns))
        L.append("        %s::LEGS, std::size(%s::LEGS)," % (ns, ns))
        L.append("        %s::LEG_LISTS, std::size(%s::LEG_LISTS)," % (ns, ns))
        L.append("        %s::STEPS, std::size(%s::STEPS)," % (ns, ns))
        L.append("        %s::SEGMENTS, std::size(%s::SEGMENTS)," % (ns, ns))
        L.append("        %s::MAP_NAMES, std::size(%s::MAP_NAMES)," % (ns, ns))
        L.append("    };")
        L.append("    return script;")
        L.append("}")
        L.append("")
    #  Which story data a build has: the program logs it when it starts.
    import hashlib
    digest = hashlib.sha1("\n".join(L).encode("utf-8")).hexdigest()[:10]
    L.append("//  A digest of all of the above.")
    L.append('inline constexpr const char* DATA_ID = "%s";' % digest)
    L.append("")
    L.append("}")
    L.append("}")
    L.append("}")
    L.append("}")
    L.append("#endif")
    with open(path, "w", newline="\r\n") as f:
        f.write("\n".join(L) + "\n")


def leg_signature(leg):
    return (tuple(leg["start"][:3]), tuple(tuple(r) for r in leg["runs"]), leg["push"], leg["face"], leg["end"])


def write_markdown(results, path, images):
    L = ["# FRLG Autostory: all segments", ""]
    L.append("Generated from the pret/pokefirered map data and `story_spec.py`.")
    L.append("")
    L.append("Run kinds: WALK = continuous, CHECKED = one step at a time, watching for a wild battle, "
             "CHECKED_TRAINER = the same for trainers, APPROACH = the same, the last moves up to a trainer "
             "that turns around (if it comes to the player, the leg ends there), BACK = back out of its line "
             "(only as far as the approach got), JUMP = ledge, SPIN = spinner tiles, SURF = surfing, "
             "DISMOUNT = off the water.")
    L.append("")
    legs_b, segs_b = results["BULBASAUR"]
    for seg in segs_b:
        L.append("## %s" % seg["id"])
        L.append("")
        L.append("%s. Start: `%s (%d,%d)`. End: `%s (%d,%d)`." % (
            seg["title"], seg["start"][0], seg["start"][1], seg["start"][2], seg["end"][0], seg["end"][1], seg["end"][2]))
        L.append("")
        for st in seg["steps"]:
            if st["type"] == "WALK":
                leg = legs_b[st["leg"]]
                runs = " ".join("%s%d%s" % (d[0].upper(), n, "" if k == "WALK" else "(" + k.lower() + ")") for d, n, k in leg["runs"])
                extra = ""
                if leg["push"]:
                    extra += " -> warp (%s)" % leg["push"]
                if leg["end"] == "WARP_STEP":
                    extra += " -> warp"
                if leg["face"]:
                    extra += " -> face %s" % leg["face"]
                if leg["end"] == "TRIGGER":
                    extra += " -> trigger"
                L.append("- WALK `%s`: %s%s" % (leg["name"], runs or "(stand still)", extra))
                for img in images.get(("BULBASAUR", leg["id"]), []):
                    L.append("  - ![](images/%s)" % img)
            else:
                L.append("- %s: %s%s" % (st["type"], st.get("label", ""),
                                         (" (%s)" % st["text"]) if st.get("text") else ""))
        L.append("")
    with open(path, "w") as f:
        f.write("\n".join(L))


def render_images(decomp, results, out_dir):
    from render import Renderer
    from PIL import Image, ImageDraw
    r = Renderer(decomp)
    images = {}
    os.makedirs(os.path.join(out_dir, "images"), exist_ok=True)
    seen = {}
    base_cache = {}
    for variant, (legs, segs) in results.items():
        for leg in legs:
            sig = leg_signature(leg)
            if variant != "BULBASAUR" and sig in seen:
                continue
            seen[sig] = True
            #  Split points by map.
            per_map = []
            for (mid, x, y) in leg["points"]:
                if not per_map or per_map[-1][0] != mid:
                    per_map.append((mid, []))
                per_map[-1][1].append((x, y))
            files = []
            for i, (mid, pts) in enumerate(per_map):
                m = decomp.maps[mid]
                if mid not in base_cache:
                    base_cache[mid] = r.render_map(m, 2)
                img = base_cache[mid].copy().convert("RGBA")
                dr = ImageDraw.Draw(img)
                s = 32
                ps = [(x * s + 16, y * s + 16) for x, y in pts]
                if len(ps) >= 2:
                    dr.line(ps, fill=(255, 0, 0, 255), width=4)
                if ps:
                    x0, y0 = ps[0]
                    dr.ellipse([x0 - 6, y0 - 6, x0 + 6, y0 + 6], fill=(255, 255, 255, 255), outline=(255, 0, 0, 255), width=2)
                    x1, y1 = ps[-1]
                    dr.rectangle([x1 - 6, y1 - 6, x1 + 6, y1 + 6], fill=(255, 0, 0, 255))
                title = "%s %d %s - %s" % (variant, leg["id"], leg["name"], m.name)
                bar = Image.new("RGBA", (img.width, 18), (20, 20, 20, 255))
                ImageDraw.Draw(bar).text((4, 3), title, fill=(255, 255, 255, 255))
                full = Image.new("RGBA", (img.width, img.height + 18))
                full.paste(bar, (0, 0))
                full.paste(img, (0, 18))
                fname = "%s_%04d_%s_%d.png" % (variant, leg["id"], m.name, i)
                full.convert("RGB").save(os.path.join(out_dir, "images", fname), optimize=True)
                files.append(fname)
            images[(variant, leg["id"])] = files
    return images


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--decomp", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--no-images", action="store_true")
    ap.add_argument("--variants", default="BULBASAUR,SQUIRTLE,CHARMANDER")
    args = ap.parse_args()

    decomp = Decomp(args.decomp)
    gd = GameData(decomp)
    spec = story_spec.spec()
    results = {}
    os.makedirs(args.out, exist_ok=True)
    failed = False
    for variant in args.variants.split(","):
        b = Builder(decomp, gd, variant)
        try:
            segs = b.build(spec)
        except StoryError as e:
            print("ERROR: %s" % e, file=sys.stderr)
            failed = True
            continue
        results[variant] = (b.legs, segs)
        steps = sum(len(s["steps"]) for s in segs)
        walk = sum(sum(n * (2 if k == "JUMP" else 1) for d, n, k in l["runs"]) for l in b.legs)
        checked = sum(l["encounter_steps"] + l["trainer_steps"] for l in b.legs)
        print("%-11s %3d segments, %4d steps, %4d legs, %5d tiles walked, %4d checked steps" % (
            variant, len(segs), steps, len(b.legs), walk, checked))
        for w in b.warnings:
            print("  WARNING: %s" % w)
    if failed:
        sys.exit(1)
    with open(os.path.join(args.out, "story.json"), "w") as f:
        json.dump({v: {"legs": [{k: val for k, val in l.items() if k != "points"} for l in legs], "segments": segs}
                   for v, (legs, segs) in results.items()}, f, indent=1)
    write_cpp(results, os.path.join(args.out, "PokemonFRLG_AutoStoryData.h"), decomp)
    images = {} if args.no_images else render_images(decomp, results, args.out)
    if "BULBASAUR" in results:
        write_markdown(results, os.path.join(args.out, "STORY.md"), images)


if __name__ == "__main__":
    main()
